const assert = require('assert')
const fs = require('fs')
const path = require('path')
const { createRequire } = require('module')
const api = require('../docs/.vuepress/api/question-bank')
const compiler = require('vue-template-compiler')

async function run () {
  const first = await api.getQuestions({ page: 1, pageSize: 20 })
  assert.strictEqual(first.total, 64)
  assert.strictEqual(first.list.length, 20)
  assert(!('answer' in first.list[0]))
  const last = await api.getQuestions({ page: 999, pageSize: 20 })
  assert.strictEqual(last.page, 4)
  assert.strictEqual(last.list.length, 4)
  const all = []
  for (let page = 1; page <= 4; page++) all.push(...(await api.getQuestions({ page })).list)
  assert.strictEqual(new Set(all.map(q => q.id)).size, 64)
  assert.strictEqual((await api.getQuestions({ keyword: '不存在的搜索词xyz' })).total, 0)
  const detail = await api.getQuestion(first.list[0].id)
  assert(detail.explanation.includes('逐项解析'))
  await assert.rejects(() => api.getQuestion('missing'))

  const file = path.resolve(__dirname, '../docs/.vuepress/api/question-bank-controller.js')
  const moduleObject = { exports: {} }
  new Function('require', 'module', fs.readFileSync(file, 'utf8').replace('export default', 'module.exports ='))(createRequire(file), moduleObject)
  const definition = moduleObject.exports, state = definition.data()
  Object.entries(definition.methods).forEach(([key, fn]) => { state[key] = fn.bind(state) })
  Object.entries(definition.computed).forEach(([key, fn]) => Object.defineProperty(state, key, { get: () => fn.call(state) }))
  await state.loadPage(1); state.view = 'list'; await state.start(19); await state.move(1)
  assert.strictEqual(state.page, 2); assert.strictEqual(state.position, 20)
  await state.move(-1); assert.strictEqual(state.page, 1); assert.strictEqual(state.position, 19)
  state.current = detail
  state.selected = []; state.submitted = false; state.revealed = false
  assert.strictEqual(state.showAnswer, false)
  state.revealAnswer()
  assert.strictEqual(state.showAnswer, true)
  assert.strictEqual(state.submitted, false)
  state.toggle(detail.answer[0]); assert.deepStrictEqual(state.selected, [])
  state.toggleStudyMode()
  assert.strictEqual(state.studyMode, true)
  assert.strictEqual(state.optionClass(detail.answer[0])['study-correct'], true)
  await state.start(0)
  assert.strictEqual(state.studyMode, true)
  assert.strictEqual(state.showAnswer, true)
  await state.move(1)
  assert.strictEqual(state.showAnswer, true)
  state.toggleStudyMode()
  assert.strictEqual(state.showAnswer, false)
  state.revealAnswer(); await state.start(0)
  assert.strictEqual(state.revealed, false)
  state.current = detail
  assert(state.analysisHtml.includes('<h3>逐项解析</h3>'))
  state.current = { ...detail, explanation: '<script>alert(1)</script>' }
  assert(!state.analysisHtml.includes('<script>'))
  const sfc = compiler.parseComponent(fs.readFileSync(path.resolve(__dirname, '../docs/.vuepress/components/QuestionBank.vue'), 'utf8'))
  assert.deepStrictEqual(sfc.errors || [], [])
  assert.deepStrictEqual(compiler.compile(sfc.template.content).errors, [])
  console.log('PASS: 分页/去重/搜索/详情/跨页答题/Markdown安全渲染/Vue模板')
}
run().catch(error => { console.error(error); process.exitCode = 1 })
